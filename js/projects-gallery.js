// ---- Render Photo Gallery ----
function renderPhotoGallery() {
  const container = document.getElementById('photo-gallery');
  if (!container) return;
  container.innerHTML = galleryImages.map((src, i) => {
    const thumbSrc = src.startsWith('http') ? src + '?format=750w' : src;
    return `
    <div class="photo-gallery__item" data-gallery-index="${i}">
      <img src="${thumbSrc}" alt="Project photo" loading="lazy">
    </div>`;
  }).join('');
}

// ---- Render Project Cards (featured only) ----
function renderProjectCards() {
  const grid = document.getElementById('projects-grid');
  if (!grid) return;

  const featured = projects.filter(p => FEATURED_IDS.includes(p.id));
  grid.innerHTML = featured.map(project => {
    const coverSrc = project.cover || '';
    const imgHTML = coverSrc
      ? `<img src="${coverSrc}" alt="${project.title}" loading="lazy" style="width:100%;height:100%;object-fit:cover;">`
      : `<div class="placeholder-img" style="width:100%;height:100%;">Project Photo</div>`;
    return `
      <div class="project-card reveal" data-category="${project.category}" data-project-id="${project.id}">
        <div class="project-card__image img-zoom">${imgHTML}</div>
        <div class="project-card__overlay"></div>
        <div class="project-card__info">
          <span class="project-card__category">${project.categoryLabel}</span>
          <h3 class="project-card__title">${project.title}</h3>
          <span class="project-card__link">View Project &rarr;</span>
        </div>
      </div>`;
  }).join('');

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('revealed');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15, rootMargin: '0px 0px -50px 0px' });
  grid.querySelectorAll('.reveal').forEach(el => observer.observe(el));
}

// ---- Page Tab Switching ----
function initPageTabs() {
  const tabs = document.querySelectorAll('.page-tab');
  if (!tabs.length) return;

  function activateTab(panelName) {
    tabs.forEach(t => t.classList.toggle('active', t.dataset.panel === panelName));
    document.querySelectorAll('.tab-panel').forEach(p => p.classList.remove('tab-panel--active'));
    const target = document.getElementById('panel-' + panelName);
    if (target) target.classList.add('tab-panel--active');
  }

  // Read hash on load so direct links and back/forward work
  function panelFromHash() {
    const hash = location.hash.replace('#', '');
    return hash === 'recent' ? 'recent' : 'gallery';
  }

  activateTab(panelFromHash());

  tabs.forEach(tab => {
    tab.addEventListener('click', () => {
      location.hash = tab.dataset.panel;
    });
  });

  window.addEventListener('hashchange', () => {
    activateTab(panelFromHash());
  });
}

// ---- Gallery Lightbox ----
function initGalleryLightbox() {
  // Build overlay element
  const overlay = document.createElement('div');
  overlay.className = 'image-overlay';
  overlay.id = 'gallery-overlay';
  overlay.innerHTML = `
    <button class="image-overlay__close" aria-label="Close">&times;</button>
    <button class="image-overlay__nav image-overlay__nav--prev" aria-label="Previous">&#8249;</button>
    <img src="" alt="Gallery photo">
    <button class="image-overlay__nav image-overlay__nav--next" aria-label="Next">&#8250;</button>`;
  document.body.appendChild(overlay);

  const img = overlay.querySelector('img');
  const closeBtn = overlay.querySelector('.image-overlay__close');
  const prevBtn = overlay.querySelector('.image-overlay__nav--prev');
  const nextBtn = overlay.querySelector('.image-overlay__nav--next');
  let currentIndex = 0;

  function showImage(index) {
    currentIndex = (index + galleryImages.length) % galleryImages.length;
    img.src = galleryImages[currentIndex];
    overlay.classList.add('open');
    document.body.classList.add('modal-open');
  }

  function closeOverlay() {
    overlay.classList.remove('open');
    document.body.classList.remove('modal-open');
    img.src = '';
  }

  document.addEventListener('click', (e) => {
    const item = e.target.closest('.photo-gallery__item');
    if (!item) return;
    showImage(parseInt(item.dataset.galleryIndex, 10));
  });

  prevBtn.addEventListener('click', () => showImage(currentIndex - 1));
  nextBtn.addEventListener('click', () => showImage(currentIndex + 1));
  closeBtn.addEventListener('click', closeOverlay);
  overlay.addEventListener('click', (e) => { if (e.target === overlay) closeOverlay(); });
  document.addEventListener('keydown', (e) => {
    if (!overlay.classList.contains('open')) return;
    if (e.key === 'Escape') closeOverlay();
    if (e.key === 'ArrowLeft') showImage(currentIndex - 1);
    if (e.key === 'ArrowRight') showImage(currentIndex + 1);
  });
}

// ---- Project Modal ----
function initModal() {
  const modal = document.getElementById('project-modal');
  if (!modal) return;
  const closeBtn = modal.querySelector('.project-modal__close');
  const header   = modal.querySelector('.project-modal__header');
  const phaseTabs = modal.querySelector('.phase-tabs');
  const gallery  = modal.querySelector('.modal-gallery');

  document.addEventListener('click', (e) => {
    const card = e.target.closest('.project-card');
    if (!card) return;
    const project = projects.find(p => p.id === card.dataset.projectId);
    if (project) openModal(project);
  });

  function openModal(project) {
    header.innerHTML = `
      <span class="project-modal__category">${project.categoryLabel}</span>
      <h2>${project.title}</h2>
      <p class="project-modal__description">${project.description}</p>`;

    phaseTabs.style.display = 'none';
    const phaseOrder = ['before', 'during', 'after'];
    const allImages = phaseOrder
      .filter(p => project.phases[p])
      .flatMap(p => project.phases[p]);
    renderModalGallery(allImages);
    modal.classList.add('open');
    document.body.classList.add('modal-open');
  }

  function renderModalGallery(images) {
    gallery.innerHTML = images.map((img, i) => `
      <div class="modal-gallery__item" data-index="${i}">
        <img src="${img.src}" alt="Project photo" loading="lazy">
      </div>`).join('');
  }

  closeBtn.addEventListener('click', closeModal);
  modal.addEventListener('click', e => { if (e.target === modal) closeModal(); });
  document.addEventListener('keydown', e => {
    if (e.key === 'Escape' && modal.classList.contains('open')) closeModal();
  });
  function closeModal() {
    modal.classList.remove('open');
    document.body.classList.remove('modal-open');
  }
}
